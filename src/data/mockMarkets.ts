// Helper to generate realistic candles
function generateCandles(basePrice: number, count: number = 30, volatility: number = 0.015): Candle[] {
  const candles: Candle[] = [];
  let current = basePrice * 0.95;
  const now = new Date();

  for (let i = count; i >= 0; i--) {
    const d = new Date(now.getTime() - i * 24 * 60 * 60 * 1000);
    const dayStr = d.toLocaleDateString('en-US', { month: 'short', day: 'numeric' });
    
    const change = (Math.random() - 0.48) * volatility * current;
    const open = current;
    const close = Math.max(open + change, 0.001);
    const high = Math.max(open, close) + Math.random() * volatility * current * 0.8;
    const low = Math.min(open, close) - Math.random() * volatility * current * 0.8;
    const volume = Math.floor(Math.random() * 5000000 + 1000000);

    candles.push({
      time: dayStr,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume
    });

    current = close;
  }
  return candles;
}

